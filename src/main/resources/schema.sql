CREATE TABLE IF NOT EXISTS processing_lock (id INT PRIMARY KEY);
INSERT INTO processing_lock (id) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM processing_lock WHERE id = 1);
CREATE TABLE IF NOT EXISTS accounts (
    account_id VARCHAR(100) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    balance DECIMAL(38,2) NOT NULL DEFAULT 0,
    next_sequence BIGINT NOT NULL DEFAULT 1,
    PRIMARY KEY (account_id, currency)
);
CREATE TABLE IF NOT EXISTS transactions (
    transaction_id VARCHAR(100) PRIMARY KEY,
    account_id VARCHAR(100) NOT NULL,
    transaction_type VARCHAR(10) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    sequence_number BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    error_code VARCHAR(100),
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (account_id, currency, sequence_number),
    FOREIGN KEY (account_id, currency) REFERENCES accounts(account_id, currency)
);
CREATE TABLE IF NOT EXISTS request_keys (
    request_id VARCHAR(100) PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL REFERENCES transactions(transaction_id)
);
CREATE TABLE IF NOT EXISTS ledger (
    transaction_id VARCHAR(100) PRIMARY KEY REFERENCES transactions(transaction_id),
    account_id VARCHAR(100) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    delta DECIMAL(19,2) NOT NULL,
    balance_after DECIMAL(38,2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_transaction_due ON transactions(status, next_attempt_at);

-- Additive compatibility for databases created by the initial implementation.
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS opening_balance DECIMAL(19,2) NOT NULL DEFAULT 0;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS starting_sequence BIGINT NOT NULL DEFAULT 1;
ALTER TABLE request_keys ADD COLUMN IF NOT EXISTS outcome VARCHAR(20) NOT NULL DEFAULT 'ACCEPTED';
ALTER TABLE request_keys ADD COLUMN IF NOT EXISTS replay_count BIGINT NOT NULL DEFAULT 0;
ALTER TABLE request_keys ADD COLUMN IF NOT EXISTS received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;
CREATE TABLE IF NOT EXISTS processing_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL REFERENCES transactions(transaction_id),
    attempt_number INT NOT NULL,
    outcome VARCHAR(30) NOT NULL,
    error_code VARCHAR(100),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_attempt_transaction ON processing_attempts(transaction_id, id);

ALTER TABLE transactions ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
